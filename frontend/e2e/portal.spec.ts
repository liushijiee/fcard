import { expect, test, type Page } from '@playwright/test'

async function userLogin(page: Page, email: string, password: string): Promise<void> {
  await page.goto('/portal/login')
  await page.getByLabel('用户邮箱').fill(email)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录用户空间', exact: true }).click()
}

test('real M1.5 account initialization, forced change, session isolation and revocation', async ({ page }) => {
  test.skip(!process.env.FCARD_E2E_PASSWORD, 'Run scripts/test-frontend-integration.ps1 for an isolated database and Go backend')
  const temporary = 'E2e-temporary-password-123'
  const permanent = 'E2e-permanent-password-456'
  const email = 'portal-e2e@example.com'
  await page.goto('/login')
  await page.getByLabel('管理员邮箱').fill('e2e@fcard.test')
  await page.getByLabel('密码', { exact: true }).fill(process.env.FCARD_E2E_PASSWORD!)
  await page.getByRole('button', { name: '进入控制台' }).click()
  await page.getByRole('link', { name: '用户管理', exact: true }).click()
  await page.getByRole('button', { name: '创建用户', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('显示名称').fill('用户侧联调账号')
  await dialog.getByLabel('邮箱地址').fill(email)
  await dialog.getByRole('button', { name: '确认创建' }).click()
  const row = page.getByRole('row').filter({ hasText: email })
  await expect(row).toContainText('未开通登录')
  await row.getByRole('button', { name: '开通登录' }).click()
  await dialog.getByLabel('临时密码', { exact: true }).fill(temporary)
  await dialog.getByLabel('确认临时密码').fill(temporary)
  await dialog.getByRole('button', { name: '确认设置临时密码' }).click()
  await expect(row).toContainText('待首次改密')
  await userLogin(page, email, temporary)
  await expect(page.getByRole('heading', { name: '请先修改临时密码' })).toBeVisible()
  await page.getByRole('link', { name: '个人账号', exact: true }).click()
  await expect(page).toHaveURL(/\/portal\/security$/)
  await page.evaluate(() => {
    const value = JSON.parse(sessionStorage.getItem('fcard.user.session')!)
    value.user.must_change_password = false
    sessionStorage.setItem('fcard.user.session', JSON.stringify(value))
  })
  await page.goto('/portal')
  await expect(page.getByRole('heading', { name: '请先修改临时密码' })).toBeVisible()
  await page.getByLabel('当前密码', { exact: true }).fill(temporary)
  await page.getByLabel('新密码', { exact: true }).fill(permanent)
  await page.getByLabel('确认新密码').fill(permanent)
  await page.getByRole('button', { name: '修改密码并重新登录' }).click()
  await expect(page.getByRole('heading', { name: '登录用户空间' })).toBeVisible()
  await expect.poll(() => page.evaluate(() => Boolean(sessionStorage.getItem('fcard.user.session')))).toBe(false)
  expect(await page.evaluate(() => Boolean(sessionStorage.getItem('fcard.admin.session')))).toBe(true)
  await userLogin(page, email, permanent)
  await expect(page.getByRole('heading', { name: '你好，用户侧联调账号' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: '你好，用户侧联调账号' })).toBeVisible()
  await page.goto('/portal/cards')
  await expect(page.getByText('管理员尚未启用沙盒开卡。')).toBeVisible()
  await expect(page.getByRole('button', { name: '申请沙盒虚拟卡' })).toBeDisabled()
  await page.getByRole('link', { name: '管理控制台' }).click()
  await page.getByRole('link', { name: '用户管理', exact: true }).click()
  await row.getByRole('button', { name: '重置密码' }).click()
  await dialog.getByLabel('临时密码', { exact: true }).fill(temporary)
  await dialog.getByLabel('确认临时密码').fill(temporary)
  await dialog.getByRole('button', { name: '确认设置临时密码' }).click()
  await expect(dialog).not.toBeVisible()
  await page.goto('/portal')
  await expect(page.getByRole('heading', { name: '登录用户空间' })).toBeVisible()
  await userLogin(page, email, temporary)
  await expect(page.getByRole('heading', { name: '请先修改临时密码' })).toBeVisible()
  await page.goto('/users')
  await row.getByRole('button', { name: '停用', exact: true }).click()
  await dialog.getByRole('button', { name: '确认停用' }).click()
  await expect(row).toContainText('已停用')
  await page.goto('/portal')
  await expect(page.getByRole('heading', { name: '登录用户空间' })).toBeVisible()
  await page.goto('/users')
  await row.getByRole('button', { name: '启用', exact: true }).click()
  await dialog.getByRole('button', { name: '确认启用' }).click()
  await expect(row).toContainText('正常')
  await userLogin(page, email, temporary)
  await expect(page.getByRole('heading', { name: '请先修改临时密码' })).toBeVisible()
  await page.getByRole('button', { name: '退出用户登录' }).click()
  await expect(page.getByRole('heading', { name: '登录用户空间' })).toBeVisible()
  await page.goto('/users')
  await expect(row).toBeVisible()
  await userLogin(page, email, temporary)
  await expect(page.getByRole('heading', { name: '请先修改临时密码' })).toBeVisible()
  await page.goto('/')
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登录管理控制台' })).toBeVisible()
  await page.goto('/portal/security')
  await expect(page.getByRole('heading', { name: '请先修改临时密码' })).toBeVisible()
  expect(await page.evaluate(() => Boolean(sessionStorage.getItem('fcard.admin.session')))).toBe(false)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/portal-security-mobile.png' })
})
